export function inferLibraryRepeat(
  task: Pick<ChoremaxxLibraryTask, 'id' | 'title' | 'group' | 'domain' | 'frequency'>,
): 'Daily' | 'Weekly' | 'Weekdays' | 'None' {
  if (task.frequency) {
    const fromFreq: Record<string, 'Daily' | 'Weekly' | 'Weekdays' | 'None'> = {
      daily: 'Daily',
      weekdays: 'Weekdays',
      '2x_weekly': 'Weekly',
      weekly: 'Weekly',
      biweekly: 'Weekly',
      monthly: 'Weekly',
      quarterly: 'None',
      seasonal: 'None',
      as_needed: 'None',
    };
    const mapped = fromFreq[task.frequency];
    if (mapped) return mapped;
  }
  const mapped = LIBRARY_REPEAT_BY_ID[task.id];
  if (mapped) return mapped;
  return 'Weekly';
}

export function isHygieneLibraryTask(task: Pick<ChoremaxxLibraryTask, 'domain' | 'tracking' | 'audience'>): boolean {
  return task.domain === 'Hygiene' || task.tracking === 'streak' || task.audience === 'child';
}

export function libraryDomains(
  audience: LibraryAudience | 'all' = 'all',
  opts?: { includeChildOnly?: boolean },
): string[] {
  const includeChild = opts?.includeChildOnly ?? (audience === "child" || audience === "all");
  const seen = new Set<string>();
  const out: string[] = [];
  for (const task of CHOREMAXX_TASK_LIBRARY) {
    if (task.audience === "child") {
      if (!includeChild) continue;
    } else if (audience !== "all" && task.audience !== "both" && task.audience !== audience) {
      continue;
    }
    if (!seen.has(task.domain)) {
      seen.add(task.domain);
      out.push(task.domain);
    }
  }
  return out;
}

export function filterLibraryTasks(opts: {
  audience?: LibraryAudience | 'all';
  domain?: string | null;
  query?: string;
  /** When false, hide kids-only Hygiene (default false for roommate/guest flows). */
  includeChildOnly?: boolean;
}): ChoremaxxLibraryTask[] {
  const audience = opts.audience ?? 'all';
  const includeChild = opts.includeChildOnly ?? (audience === "child");
  const q = (opts.query ?? '').trim().toLowerCase();
  return CHOREMAXX_TASK_LIBRARY.filter((task) => {
    if (task.audience === "child") {
      if (!includeChild) return false;
    } else if (audience !== "all" && task.audience !== "both" && task.audience !== audience) {
      return false;
    }
    if (opts.domain && task.domain !== opts.domain) return false;
    if (!q) return true;
    const hay = `${task.title} ${task.group} ${task.domain} ${task.aliases ?? ''}`.toLowerCase();
    return hay.includes(q);
  });
}

