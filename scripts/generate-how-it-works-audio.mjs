#!/usr/bin/env node
/**
 * Bake How-it-works audio once with OpenAI GPT conversational voice.
 *
 * This is NOT device TTS and NOT classic robotic tts-1. It uses gpt-4o-mini-tts
 * with spoken instructions so Rose (you) and Indigo (Poppins) sound like a real
 * chat — generate once, commit the m4a files, ship offline forever.
 *
 *   OPENAI_API_KEY=sk-... node scripts/generate-how-it-works-audio.mjs
 *
 * Optional:
 *   OPENAI_TTS_MODEL=gpt-4o-mini-tts
 *   OPENAI_TTS_ROSE=coral          # warmer asker
 *   OPENAI_TTS_INDIGO=sage        # calmer Poppins
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'assets/how-it-works');
const scriptPath = join(root, 'lib/poppins/how-it-works-script.ts');
const audioTsPath = join(root, 'lib/poppins/how-it-works-audio.ts');

const apiKey = process.env.OPENAI_API_KEY?.trim();
if (!apiKey) {
  console.error('OPENAI_API_KEY is required to bake GPT conversational voices.');
  console.error('Add it, then re-run: OPENAI_API_KEY=sk-... node scripts/generate-how-it-works-audio.mjs');
  process.exit(1);
}

const model = process.env.OPENAI_TTS_MODEL?.trim() || 'gpt-4o-mini-tts';
const roseVoice = process.env.OPENAI_TTS_ROSE?.trim() || 'coral';
const indigoVoice = process.env.OPENAI_TTS_INDIGO?.trim() || 'sage';

const INSTRUCTIONS = {
  rose:
    'You are a real parent talking casually to a household assistant named Poppins. Speak clear modern American English, warm and natural, as if on a phone call. Never sound robotic or like you are reading a label. Use gentle pacing and natural emphasis.',
  indigo:
    'You are Poppins, a calm household co-manager answering a parent. Speak clear modern American English, confident and friendly, like ChatGPT Advanced Voice. Confirm what you understood in full sentences. Never sound robotic or clipped.',
};

/** Pull DEMO_BEATS spoken lines from the TypeScript source without importing RN. */
function loadBeats() {
  const src = readFileSync(scriptPath, 'utf8');
  // Scope to DEMO_BEATS only — DEMO_CHAPTERS also has `{ id: 'task' … }` and
  // would steal the first spoken line from `task-ask` if we scanned the whole file.
  const start = src.indexOf('export const DEMO_BEATS');
  if (start < 0) throw new Error('DEMO_BEATS not found in how-it-works-script.ts');
  const end = src.indexOf('export function', start);
  const slice = end > start ? src.slice(start, end) : src.slice(start);
  const beats = [];
  const re =
    /\{\s*id:\s*'([^']+)'[\s\S]*?speaker:\s*(null|'rose'|'indigo')[\s\S]*?line:\s*'((?:\\'|[^'])*)'/g;
  let match;
  while ((match = re.exec(slice))) {
    const id = match[1];
    const speakerRaw = match[2];
    const line = match[3].replace(/\\'/g, "'");
    if (speakerRaw === 'null') continue;
    const speaker = speakerRaw.replace(/'/g, '');
    beats.push({ id, speaker, line });
  }
  if (beats.length < 8) {
    throw new Error(`Parsed only ${beats.length} spoken beats — check how-it-works-script.ts`);
  }
  if (!beats.some((b) => b.id === 'task-ask')) {
    throw new Error('Expected spoken beat id task-ask — DEMO_CHAPTERS may have leaked into the parse');
  }
  return beats;
}

async function synthesize({ id, speaker, line }) {
  const voice = speaker === 'rose' ? roseVoice : indigoVoice;
  const instructions = INSTRUCTIONS[speaker];
  const res = await fetch('https://api.openai.com/v1/audio/speech', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${apiKey}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      model,
      voice,
      input: line,
      instructions,
      response_format: 'wav',
    }),
  });
  if (!res.ok) {
    const detail = await res.text();
    throw new Error(`${id} ${res.status}: ${detail.slice(0, 400)}`);
  }
  return Buffer.from(await res.arrayBuffer());
}

function wavToM4a(wavPath, m4aPath) {
  execFileSync(
    'ffmpeg',
    ['-y', '-i', wavPath, '-c:a', 'aac', '-b:a', '96k', '-ac', '1', '-ar', '44100', m4aPath],
    { stdio: 'pipe' }
  );
}

function writeAudioModule(ids) {
  const lines = ids.map((id) => `  '${id}': require('@/assets/how-it-works/${id}.m4a'),`).join('\n');
  const body = `/**
 * Recorded GPT conversational lines for the How it works demo.
 *
 * Generated by scripts/generate-how-it-works-audio.mjs (gpt-4o-mini-tts).
 * Do not fall back to device Speech for this demo — the whole point is human-sounding chat.
 */

const RECORDINGS: Record<string, number> = {
${lines}
};

/** True once any line has been recorded — the player picks its path from this. */
export function hasRecordedDemoAudio(): boolean {
  return Object.keys(RECORDINGS).length > 0;
}

/** The recording for a beat, or null when that line has no clip yet. */
export function recordedDemoAudio(beatId: string): number | null {
  return RECORDINGS[beatId] ?? null;
}

/** Which beats are still missing a recording — used by tests when wiring audio. */
export function missingDemoRecordings(beatIds: string[]): string[] {
  if (!hasRecordedDemoAudio()) return beatIds;
  return beatIds.filter((id) => RECORDINGS[id] == null);
}
`;
  writeFileSync(audioTsPath, body);
}

async function main() {
  try {
    execFileSync('ffmpeg', ['-version'], { stdio: 'pipe' });
  } catch {
    console.error('ffmpeg is required to convert WAV → m4a. Install it, then re-run.');
    process.exit(1);
  }

  mkdirSync(outDir, { recursive: true });
  const only = new Set(
    (process.env.HOW_IT_WORKS_ONLY ?? '')
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)
  );
  const beats = loadBeats().filter((b) => (only.size ? only.has(b.id) : true));
  if (!beats.length) {
    console.error('No beats to bake — check HOW_IT_WORKS_ONLY or DEMO_BEATS.');
    process.exit(1);
  }
  console.log(`Baking ${beats.length} GPT voice lines (${model}; rose=${roseVoice}, indigo=${indigoVoice})`);

  // When rebaking a subset, keep every id already wired in RECORDINGS.
  const existingIds = (() => {
    if (!existsSync(audioTsPath)) return [];
    return [...readFileSync(audioTsPath, 'utf8').matchAll(/'([^']+)':\s*require\(/g)].map((m) => m[1]);
  })();
  const ids = only.size ? [...new Set([...existingIds, ...beats.map((b) => b.id)])] : [];
  for (const beat of beats) {
    process.stdout.write(`  ${beat.id}… `);
    const wav = await synthesize(beat);
    const wavPath = join(outDir, `${beat.id}.wav`);
    const m4aPath = join(outDir, `${beat.id}.m4a`);
    writeFileSync(wavPath, wav);
    wavToM4a(wavPath, m4aPath);
    try {
      const { unlinkSync } = await import('node:fs');
      unlinkSync(wavPath);
    } catch {
      /* keep wav if unlink fails */
    }
    if (!existsSync(m4aPath)) throw new Error(`missing ${m4aPath}`);
    if (!only.size) ids.push(beat.id);
    console.log('ok');
  }

  writeAudioModule(only.size ? ids.sort() : ids);
  console.log(`Wrote ${ids.length} clips + ${audioTsPath}`);
  console.log('Commit assets/how-it-works/*.m4a and lib/poppins/how-it-works-audio.ts');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
